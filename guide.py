# ------------------------------------------
# نرمال‌سازی متن
# ------------------------------------------

def normalize_guide_text(text):
    if not text:
        return ""

    text = str(text).strip().lower()

    # فاصله‌های خاص
    text = text.replace("\u200c", "")
    text = text.replace("\u200d", "")
    text = text.replace("\ufeff", "")

    # فاصله معمولی
    text = text.replace(" ", "")

    # علائم رایج
    punctuation = (
        "؟",
        "?",
        "!",
        "！",
        "،",
        ",",
        ".",
        "؛",
        ";",
        ":",
    )

    for char in punctuation:
        text = text.replace(char, "")

    return text


# ------------------------------------------
# تشخیص پیام راهنما
# ------------------------------------------

def is_guide_command(text):
    normalized = normalize_guide_text(text)

    if not normalized:
        return False

    return normalized in {
        normalize_guide_text(command)
        for command in GUIDE_COMMANDS
    }


